    private PairingDisplayNamePolicy() { }

    static String validate(String name) {
        if (name == null) return null;
        // Every legal UTF-16 string has at least as many UTF-8 bytes as code units.
        if (name.isEmpty() || name.length() > 128) throw invalid();
        int bytes = 0;
        boolean nonblank = false;
        for (int offset = 0; offset < name.length();) {
            char first = name.charAt(offset++);
            int scalar;
            if (Character.isHighSurrogate(first)) {
                if (offset == name.length() || !Character.isLowSurrogate(name.charAt(offset))) throw invalid();
                scalar = Character.toCodePoint(first, name.charAt(offset++));
            } else {
                if (Character.isLowSurrogate(first)) throw invalid();
                scalar = first;
            }
            bytes += scalar <= 0x7F ? 1 : scalar <= 0x7FF ? 2 : scalar <= 0xFFFF ? 3 : 4;
            if (bytes > 128 || isControl(scalar)) throw invalid();
            nonblank |= !isWhitespace(scalar);
        }
        if (!nonblank) throw invalid();
        return name; // No normalization, trimming, replacement or rewriting.
    }

    static boolean isValid(String name) {
        try { validate(name); return true; }
        catch (IllegalArgumentException ignored) { return false; }
    }
    static boolean isControl(int scalar) { return contains(CONTROL_RANGES, scalar); }
    static boolean isWhitespace(int scalar) { return contains(WHITESPACE_RANGES, scalar); }

    private static boolean contains(int[][] ranges, int scalar) {
        if (scalar < 0 || scalar > 0x10FFFF || (scalar >= 0xD800 && scalar <= 0xDFFF)) throw invalid();
        int low = 0, high = ranges.length - 1;
        while (low <= high) {
            int middle = low + ((high - low) >>> 1);
            if (scalar < ranges[middle][0]) high = middle - 1;
            else if (scalar > ranges[middle][1]) low = middle + 1;
            else return true;
        }
        return false;
    }
